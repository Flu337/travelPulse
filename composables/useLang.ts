export function useLang() {
  const lang = useState<LangCode>('site-lang', () => 'RUS')
  const t = computed(() => dict[lang.value])
  const otherLangs = computed(() => (['RUS', 'ENG', '中国人'] as LangCode[]).filter((l) => l !== lang.value))

  function setLang(code: LangCode) {
    lang.value = code
  }

  return { lang, t, otherLangs, setLang }
}
